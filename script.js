function saveLanguagePreference() {
  localStorage.setItem('feather-care-language', state.currentLanguage);
}

function applyTranslations() {
  const dictionary = translations[state.currentLanguage];
  document.documentElement.lang = state.currentLanguage === 'ar' ? 'ar' : 'en';
  document.documentElement.dir = state.currentLanguage === 'ar' ? 'rtl' : 'ltr';
  document.body.dir = state.currentLanguage === 'ar' ? 'rtl' : 'ltr';

  const nodes = document.querySelectorAll('[data-i18n]');
  nodes.forEach((node) => {
    const key = node.dataset.i18n;
    if (dictionary[key]) {
      node.textContent = dictionary[key];
    }
  });

  const placeholderNodes = document.querySelectorAll('[data-i18n-placeholder]');
  placeholderNodes.forEach((node) => {
    const key = node.dataset.i18nPlaceholder;
    if (dictionary[key]) node.setAttribute('placeholder', dictionary[key]);
  });

  const ariaNodes = document.querySelectorAll('[data-i18n-aria]');
  ariaNodes.forEach((node) => {
    const key = node.dataset.i18nAria;
    if (dictionary[key]) node.setAttribute('aria-label', dictionary[key]);
  });

  const btn = document.querySelector('.language-toggle');
  if (btn) {
    btn.textContent = translations[state.currentLanguage]['nav.languageToggle'];
  }
}

function toggleLanguage() {
  state.currentLanguage = state.currentLanguage === 'en' ? 'ar' : 'en';
  saveLanguagePreference();
  applyTranslations();
}

