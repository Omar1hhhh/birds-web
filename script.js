function formatEGP(value) {
  return new Intl.NumberFormat('en-EG', { style: 'currency', currency: 'EGP', maximumFractionDigits: 0 }).format(value);
}

function saveCart() {
  localStorage.setItem('feather-care-cart', JSON.stringify(state.cart));
}

function saveWishlist() {
  localStorage.setItem('feather-care-wishlist', JSON.stringify([...state.wishlist]));
}

function updateCartCount() {
  const total = state.cart.reduce((sum, item) => sum + item.quantity, 0);
  document.querySelectorAll('.cart-count').forEach((counter) => {
    counter.textContent = total;
  });
}

function renderHeaderCartBadge() {
  updateCartCount();
}

function addToCart(productId, quantity = 1) {
  const existing = state.cart.find((item) => item.id === productId);
  if (existing) {
    existing.quantity += quantity;
  } else {
    state.cart.push({ id: productId, quantity });
  }
  saveCart();
  renderCart();
  openCart();
}

function removeFromCart(productId) {
  state.cart = state.cart.filter((item) => item.id !== productId);
  saveCart();
  renderCart();
}

function changeQuantity(productId, delta) {
  const item = state.cart.find((entry) => entry.id === productId);
  if (!item) return;
  item.quantity += delta;
  if (item.quantity <= 0) {
    removeFromCart(productId);
    return;
  }
  saveCart();
  renderCart();
}

function openCart() {
  const cartDrawer = document.querySelector('.cart-drawer');
  const cartOverlay = document.querySelector('.cart-overlay');
  if (!cartDrawer || !cartOverlay) return;
  cartDrawer.classList.add('open');
  cartOverlay.classList.add('visible');
}

function closeCart() {
  const cartDrawer = document.querySelector('.cart-drawer');
  const cartOverlay = document.querySelector('.cart-overlay');
  if (!cartDrawer || !cartOverlay) return;
  cartDrawer.classList.remove('open');
  cartOverlay.classList.remove('visible');
}

function renderCart() {
  const cartItems = document.querySelector('.cart-items');
  const emptyCart = document.querySelector('.empty-cart');
  const subtotalAmount = document.querySelector('.subtotal-amount');
  const total = document.querySelector('.cart-total-amount');

  if (!cartItems || !emptyCart || !subtotalAmount || !total) return;

  const dictionary = translations[state.currentLanguage];
  if (!state.cart.length) {
    cartItems.innerHTML = '';
    emptyCart.textContent = dictionary['cart.emptyState'];
    emptyCart.classList.add('visible');
    subtotalAmount.textContent = formatEGP(0);
    total.textContent = formatEGP(0);
    updateCartCount();
    return;
  }

  emptyCart.classList.remove('visible');
  const subtotal = state.cart.reduce((sum, item) => {
    const product = productCatalog.find((entry) => entry.id === item.id);
    return sum + (product ? product.price * item.quantity : 0);
  }, 0);

  cartItems.innerHTML = state.cart.map((item) => {
    const product = productCatalog.find((entry) => entry.id === item.id);
    if (!product) return '';
    return `
      <div class="cart-row">
        <div class="cart-thumb" style="background-image:url('${product.image}')"></div>
        <div>
          <h4>${product.name}</h4>
          <div class="qty-controls">
            <button type="button" data-action="decrease" data-id="${product.id}">-</button>
            <span>${item.quantity}</span>
            <button type="button" data-action="increase" data-id="${product.id}">+</button>
          </div>
        </div>
        <div>
          <strong>${formatEGP(product.price * item.quantity)}</strong>
          <div><button type="button" class="remove-item" data-id="${product.id}" style="background:none;border:0;color:var(--muted);margin-top:8px;">${dictionary['product.remove']}</button></div>
        </div>
      </div>
    `;
  }).join('');

  subtotalAmount.textContent = formatEGP(subtotal);
  total.textContent = formatEGP(subtotal);
  updateCartCount();
}

