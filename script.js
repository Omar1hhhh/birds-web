function wireGlobalEvents() {
  document.addEventListener('click', (event) => {
    const target = event.target;

    if (!(target instanceof HTMLElement)) return;

    const cartTrigger = target.closest('[data-open-cart]');
    if (cartTrigger) openCart();

    const cartClose = target.closest('.cart-overlay');
    if (cartClose) closeCart();

    const cartDrawerClose = target.closest('[data-close-cart]');
    if (cartDrawerClose) closeCart();

    const closeModalButton = target.closest('.close-button');
    if (closeModalButton && !cartDrawerClose) {
      state.selectedProduct = null;
      renderProductModal(null);
    }

    const addToCartButton = target.closest('[data-add-cart]');
    if (addToCartButton) {
      addToCart(Number(addToCartButton.dataset.addCart), 1);
    }

    const removeItemButton = target.closest('.remove-item');
    if (removeItemButton) {
      removeFromCart(Number(removeItemButton.dataset.id));
    }

    const qtyAction = target.closest('[data-action]');
    if (qtyAction) {
      const id = Number(qtyAction.dataset.id);
      const action = qtyAction.dataset.action;
      if (action === 'increase') changeQuantity(id, 1);
      if (action === 'decrease') changeQuantity(id, -1);
    }

    const productDetailTrigger = target.closest('[data-open-product]');
    if (productDetailTrigger) {
      const id = Number(productDetailTrigger.dataset.openProduct);
      const product = productCatalog.find((entry) => entry.id === id);
      if (product) {
        state.selectedProduct = product;
        renderProductModal(product);
      }
    }

    const wishlistToggle = target.closest('[data-wishlist]');
    if (wishlistToggle) {
      const id = Number(wishlistToggle.dataset.wishlist);
      if (state.wishlist.has(id)) {
        state.wishlist.delete(id);
      } else {
        state.wishlist.add(id);
      }
      saveWishlist();
      renderShopProducts();
      renderProductModal(state.selectedProduct ? state.selectedProduct : null);
      document.querySelectorAll('.wishlist-button').forEach((button) => {
        button.classList.toggle('active', state.wishlist.has(Number(button.dataset.wishlist)));
      });
    }
  });

  const mobileToggle = document.querySelector('.nav-toggle');
  const mobileMenu = document.querySelector('.mobile-menu');
  if (mobileToggle && mobileMenu) {
    mobileToggle.addEventListener('click', () => {
      mobileMenu.classList.toggle('open');
    });
  }

  const filterSelect = document.querySelector('#category-filter');
  const searchInput = document.querySelector('#product-search');
  const sortSelect = document.querySelector('#sort-select');

  if (filterSelect) {
    filterSelect.addEventListener('change', (event) => {
      state.filters.category = event.target.value;
      renderShopProducts();
    });
  }

  if (searchInput) {
    searchInput.addEventListener('input', (event) => {
      state.filters.search = event.target.value;
      renderShopProducts();
    });
  }

  if (sortSelect) {
    sortSelect.addEventListener('change', (event) => {
      state.filters.sort = event.target.value;
      renderShopProducts();
    });
  }

  const filterTags = document.querySelectorAll('.filter-tag');
  filterTags.forEach((button) => {
    button.addEventListener('click', () => {
      const value = button.dataset.category;
      state.filters.category = value;
      document.querySelectorAll('.filter-tag').forEach((tag) => tag.classList.toggle('active', tag.dataset.category === value));
      if (filterSelect) filterSelect.value = value;
      renderShopProducts();
    });
  });
}

function initHeader() {
  const header = document.querySelector('.site-header');
  if (!header) return;

  const setHeaderState = () => {
    const shouldStick = window.scrollY > 8;
    header.classList.toggle('scrolled', shouldStick);
  };

  setHeaderState();
  window.addEventListener('scroll', setHeaderState, { passive: true });
}

function initRevealAnimations() {
  const elements = document.querySelectorAll('.reveal, .service-card, .product-card, .gallery-card, .article-card, .testimonial, .cta-panel, .feature-item');
  if (!('IntersectionObserver' in window)) {
    elements.forEach((element) => element.classList.add('is-visible'));
    return;
  }

  const observer = new IntersectionObserver((entries) => {
    entries.forEach((entry) => {
      if (entry.isIntersecting) {
        entry.target.classList.add('is-visible');
        observer.unobserve(entry.target);
      }
    });
  }, { threshold: 0.12 });

  elements.forEach((element) => observer.observe(element));
}

function initForms() {
  const appointmentForm = document.querySelector('#appointment-form');
  if (!appointmentForm) return;

  const message = document.querySelector('.form-message');

  appointmentForm.addEventListener('submit', (event) => {
    event.preventDefault();
    const formData = new FormData(appointmentForm);
    const requiredFields = ['customerName', 'phone', 'birdSpecies', 'birdName', 'appointmentType', 'preferredDate', 'preferredTime'];
    const missing = requiredFields.filter((field) => !String(formData.get(field) || '').trim());

    if (missing.length) {
      message.textContent = 'Please complete all required fields before submitting your request.';
      message.className = 'form-message error';
      return;
    }

    message.textContent = 'Your appointment request has been prepared for review. This demo does not send a real booking to a backend.';
    message.className = 'form-message success';
    appointmentForm.reset();
  });
}

function initNewsletter() {
  const form = document.querySelector('#newsletter-form');
  if (!form) return;

  form.addEventListener('submit', (event) => {
    event.preventDefault();
    const input = form.querySelector('input');
    const message = document.createElement('div');
    message.className = 'text-small';
    message.style.marginTop = '12px';
    message.style.color = '#E9E2D4';
    message.textContent = input && input.value.trim() ? `Thanks, ${input.value.trim()} is now on the Feather & Care updates list.` : 'Thank you for subscribing.';
    form.appendChild(message);
    form.reset();
  });
}

